def normalize_1c_text(text: str) -> str:
    text = (text or "").lower().strip()

    for k, v in OCR_REPLACEMENTS.items():
        text = text.replace(k, v)

    text = text.replace("1 c", "1с")
    text = text.replace("1c", "1с")
    text = text.replace("1с:", "1с ")
    text = text.replace("1с-", "1с ")

    text = re.sub(r"[«»\"'`]", " ", text)
    text = re.sub(r"[(){}\[\]|\\/=_~]", " ", text)
    text = re.sub(r"[^0-9a-zа-яё:\- ]+", " ", text)
    text = re.sub(r"\s+", " ", text).strip()

    return text


def similarity(a: str, b: str) -> float:
    a = normalize_1c_text(a)
    b = normalize_1c_text(b)

    if not a or not b:
        return 0.0

    if a == b:
        return 1.0

    if a in b or b in a:
        return 0.92

    return SequenceMatcher(None, a, b).ratio()


def canonicalize_1c_term(text: str) -> str:
    text_norm = normalize_1c_text(text)

    best_name = text_norm
    best_score = 0.0

    for canonical, variants in DOMAIN_SYNONYMS.items():
        candidates = [canonical] + variants
        for candidate in candidates:
            score = similarity(text_norm, candidate)
            if score > best_score:
                best_score = score
                best_name = canonical

    if best_score >= 0.62:
        return best_name

    return text.strip()


def query_to_targets(query: str) -> list[str]:
    q = normalize_1c_text(query)
    targets: list[str] = []

    for canonical, variants in DOMAIN_SYNONYMS.items():
        candidates = [canonical] + variants

